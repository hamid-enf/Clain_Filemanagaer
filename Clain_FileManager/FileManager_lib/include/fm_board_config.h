/*
 * کلیدش بالای همین فایل است: CACHE(ON) یا CACHE(OFF).
 *
 * ولی دقت کنید آن کلید چه *نمی‌کند*: کش را روشن نمی‌کند. کتابخانه
 * هیچ‌وقت SCB_EnableDCache() را صدا نمی‌زند، چون فقط شما می‌دانید
 * MPU را چطور چیده‌اید و کدام ناحیه باید کش‌دار باشد.
 *
 * کلید فقط نیت شما را ثبت می‌کند تا اگر با واقعیت نخواند به شما
 * گفته شود — مثلاً CACHE(ON) نوشته‌اید ولی SCB_EnableDCache() در
 * main.c جا مانده. نگهداری واقعیِ کش همچنان در زمان اجرا از روی
 * SCB->CCR تصمیم گرفته می‌شود، پس اگر کلید را هم اشتباه بگذارید
 * داده خراب نمی‌شود؛ فقط یک هشدار می‌گیرید.
 *
 * کش را در main.c روشن می‌کنید، با همان دستورهای همیشگی:
 *
 *     SCB_EnableICache();
 *     SCB_EnableDCache();
 *
 * و در MPU_Config() ناحیهٔ مورد نظرتان را Cacheable می‌کنید. کتابخانه
 * در زمان اجرا SCB->CCR را می‌خواند، می‌فهمد کش روشن است، و نگهداری
 * لازم برای DMA را انجام می‌دهد.
 *
 * پس هیچ ماکرویی نیست که یادتان برود تعریف کنید — حالتی وجود ندارد
 * که کش روشن باشد و کتابخانه نداند. (قبلاً بود، و دقیقاً همان باعث
 * نویز صدا و تصویر می‌شد.)
 *
 * جزئیات در include/fm_cache.h.
 */

