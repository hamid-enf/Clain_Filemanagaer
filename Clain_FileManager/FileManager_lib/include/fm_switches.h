/*
 * fm_switches.h — دو فلگ ساده
 *
 * ==================================================================
 * دو خط در fm_board_config.h. نه تابعی، نه دستوری در main().
 * ==================================================================
 *
 *     #define FM_CACHE    ON        (یا OFF)
 *     #define FM_BUFFERS  NORMAL    (یا SMALL / LARGE / HUGE)
 *
 * همین. بقیه‌اش خودکار است.
 *
 * ------------------------------------------------------------------
 * FM_CACHE
 * ------------------------------------------------------------------
 * ON  یعنی کش روشن شود. کتابخانه خودش قبل از main این کار را می‌کند
 *     (I-Cache و D-Cache) و نگهداری DMA را هم انجام می‌دهد.
 * OFF یعنی دست نزن. حالت ریست هم همین است.
 *
 * لازم نیست SCB_EnableDCache() را جایی بنویسید. اگر هم نوشته باشید
 * مشکلی پیش نمی‌آید.
 *
 * چیزی که همچنان کار شماست: MPU. کش فقط روی ناحیه‌هایی اثر دارد که
 * خودتان Cacheable کرده باشید. کتابخانه به MPU دست نمی‌زند.
 *
 * ------------------------------------------------------------------
 * FM_BUFFERS
 * ------------------------------------------------------------------
 * همهٔ بافرهای کاری را با هم مقیاس می‌کند:
 *
 *   SMALL   ÷۴   حافظه کم است
 *   NORMAL  ×۱   پیش‌فرض
 *   LARGE   ×۴   SDRAM دارید، سرعت می‌خواهید
 *   HUGE    ×۸   حداکثر
 *
 * بافرهایی که تحت تأثیرند: کپی بین دستگاه‌ها، PCM صدا، تکه‌های DMA
 * نمایشگر، خواندن ناهمگام. مقیاس نسبت به پیش‌فرضِ همان پورت است، پس
 * LARGE روی H7 و روی F1 دو چیز متفاوت‌اند.
 *
 * بافرهای فریمِ تصویر و ویدیو تحت تأثیر نیستند — آن‌ها را رزولوشن
 * تعیین می‌کند، در بخش ۳ کانفیگ.
 *
 * می‌خواهید فقط یکی را دستی عوض کنید؟ قبل از این‌ها تعریفش کنید؛
 * تعریف شما برنده است:
 *
 *     #define FM_TRANSFER_CHUNK 65536u
 */

#ifndef FM_SWITCHES_H
#define FM_SWITCHES_H

/* ------------------------------------------------------------------
 * فقط نام‌گذاری. برای استفاده لازم نیست این پایین را بخوانید.
 * ------------------------------------------------------------------ */

/*
 * ON/OFF را با #ifndef می‌گذاریم تا اگر کد خودتان یا هدرهای ST
 * قبلاً تعریفشان کرده باشند، تعریف آن‌ها را خراب نکنیم.
 */
#ifndef ON
#define ON  1
#endif
#ifndef OFF
#define OFF 0
#endif

#ifndef SMALL
#define SMALL  1
#endif
#ifndef NORMAL
#define NORMAL 2
#endif
#ifndef LARGE
#define LARGE  3
#endif
/* HUGE را <math.h> بعضی کامپایلرها هم تعریف می‌کند (نسخه‌هایی از newlib روی
 * ARM: یک عدد اعشاری). اگر آن زودتر آمده باشد دستش نمی‌زنیم؛ کتابخانه خودش هیچ‌جا با
 * این نام مقایسه نمی‌کند، بلکه با FM_BUFFERS_LEVEL (fm_buffers_level.h) که
 * مستقل از ترتیب include درست حساب می‌شود. «#define FM_BUFFERS HUGE» در هر
 * دو حالت کار می‌کند. */
#ifndef HUGE
#define HUGE   4
#endif

/* منبع diskio کارت SD: CUBEMX = sd_diskio.c کیوب دست‌نخورده.
 * FILEMANAGER = diskio کتابخانه (HAL_SD + bounce کش). */
#ifndef CUBEMX
#define CUBEMX 0
#endif
#ifndef FILEMANAGER
#define FILEMANAGER 1
#endif

#endif /* FM_SWITCHES_H */
